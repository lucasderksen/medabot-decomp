"""Replace copied code gaps with NONMATCH functions: original assembly plus the closest C.

For each named unmatched function (an .incbin gap before the end of the code
region) this writes:

- asm/non_matching/<name>.inc: the disassembly from build/m2c/<name>.s
  (tools/m2c_candidate.py), with every symbol resolved against the last
  matching build/medabots.elf;
- src/non_matching/<name>.c: the best draft from docs/drafts/<name>.c inside
  NONMATCH(...) { ... } END_NONMATCH (include/global.h), compiled with the
  profile from build/m2c/<name>/spec.json;
- a config/segments.json entry marked "nonmatching": true, which the progress
  tools count as unmatched code. tools/m2c_integrate.py replaces the entry,
  the C file and the assembly once the function matches.

    python tools/nonmatch.py sub_08048BE0 sub_08064EB4
    python tools/nonmatch.py --all
    python tools/build.py      # the full-ROM comparison verifies the assembly
"""

import argparse
import json
from pathlib import Path
import re
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import ROOT, load_segments, tool  # noqa: E402
from c_source import _definition_bounds  # noqa: E402
from m2c_integrate import headers_for, normalize  # noqa: E402

BASE = 0x08000000
SEGMENTS = ROOT / "config" / "segments.json"
SYMBOLS = ROOT / "config" / "symbols.json"
ASM_DIR = ROOT / "asm" / "non_matching"
SRC_DIR = ROOT / "src" / "non_matching"
HEADER = {".syntax", ".thumb", ".text", ".globl", ".thumb_func"}


def elf_symbols(elf=ROOT / "build" / "medabots.elf"):
    """name -> address and address -> sorted names, from the last matching build."""
    listing = subprocess.run([tool("nm"), "-n", elf], capture_output=True, text=True, check=True).stdout
    by_name, by_address = {}, {}
    for line in listing.splitlines():
        parts = line.split()
        if len(parts) != 3 or parts[1] in "tbdrn" or parts[2].startswith((".", "$")):
            continue
        address = int(parts[0], 16)
        by_name[parts[2]] = address
        by_address.setdefault(address, []).append(parts[2])
    for names in by_address.values():
        # Prefer names that say something over address placeholders.
        names.sort(key=lambda name: (name.startswith(("gUnknown_", "D_", "sub_", "data_")), len(name), name))
    return by_name, by_address


def resolve(name, by_name, by_address, branch):
    """The current symbol for a name the disassembly used; raw hex for unnamed data."""
    if name.startswith(".L") or name in by_name:
        return name
    found = re.search(r"([0-9A-Fa-f]{8})$", name)
    if found:
        address = int(found.group(1), 16)
        if by_address.get(address):
            return by_address[address][0]
        if not branch:
            return f"0x{address:08X}"
    raise ValueError(f"no symbol for {name}")


def assembly(name, start, end, by_name, by_address):
    """The function body from build/m2c/<name>.s, ready for .include inside NONMATCH."""
    source = (ROOT / "build" / "m2c" / f"{name}.s").read_text(encoding="utf-8")
    body, started = [], False
    for line in source.splitlines():
        stripped = line.strip()
        if not started:
            started = stripped == f"{name}:"
            continue
        # Capstone prints the Thumb high-register ADD Rn, SP as Rn, SP, Rn.
        line = re.sub(r"^(\s*add\s+)(r(?:[0-9]|1[0-2])),\s*sp,\s*\2\s*$", r"\1\2, sp", line)
        match = re.match(r"^(\s*(bl|\.word)\s+)([A-Za-z_.$][\w.$]*)(.*)$", line)
        if match:
            line = match.group(1) + resolve(match.group(3), by_name, by_address, match.group(2) == "bl") + match.group(4)
        body.append(line)
    if not started:
        raise ValueError(f"build/m2c/{name}.s has no label {name}:")
    return "\n".join([f"@ {name} (0x{BASE + start:08X}-0x{BASE + end:08X}, {end - start} bytes): the original code,",
                      f"@ assembled until the C in src/non_matching/{name}.c matches. Generated by tools/nonmatch.py.",
                      "\t.syntax unified", *body, "\t.syntax divided", ""])


def c_source(name):
    """src/non_matching/<name>.c around the best draft in docs/drafts/<name>.c.

    Everything before the function (declarations, types, inline helpers) is
    kept as the draft has it; only the definition is wrapped in NONMATCH.
    """
    draft = (ROOT / "docs" / "drafts" / f"{name}.c").read_text(encoding="utf-8")
    text = normalize("\n".join(line for line in draft.splitlines() if not line.lstrip().startswith("#include")))
    start, opening, end = _definition_bounds(text, name)
    if text[end:].strip():
        raise ValueError(f"docs/drafts/{name}.c: function {name} does not end the draft")
    prefix = text[:start].strip()
    signature = text[start:opening].strip()
    body = text[opening + 1:end - 1].strip("\n")
    used = set(re.findall(r"\b[A-Za-z_]\w*\b", text))
    out = ["/*", f" * {name}: not matching yet. The build assembles asm/non_matching/{name}.inc",
           " * in its place; the C below is the closest attempt (docs/drafts/README.md).", " */", ""]
    out += [f'#include "{header}"' for header in headers_for(used)] + [""]
    out += [prefix, ""] if prefix else []
    out += [f'NONMATCH("asm/non_matching/{name}.inc", {signature})', "{", body, "}", "END_NONMATCH", ""]
    return "\n".join(out)


def unmatched_gaps(segments):
    code_end = max(s["end"] for s in segments if s.get("category") != "data")
    cursor, gaps = 0, []
    for segment in segments:
        if segment["start"] > cursor and cursor < code_end:
            gaps.append((cursor, min(segment["start"], code_end)))
        cursor = max(cursor, segment["end"])
    return gaps


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("names", nargs="*", help="Functions such as sub_08048BE0")
    parser.add_argument("--all", action="store_true", help="Every .incbin gap in the code region")
    args = parser.parse_args()
    entries = json.loads(SEGMENTS.read_text(encoding="utf-8"))
    gaps = {f"sub_{BASE + start:08X}": (start, end) for start, end in unmatched_gaps(load_segments(entries=entries))}
    names = sorted(gaps) if args.all else args.names
    if not names:
        parser.error("name functions or pass --all")
    missing = [name for name in names if name not in gaps]
    if missing:
        raise SystemExit(f"Not an .incbin gap in the code region: {', '.join(missing)}")
    by_name, by_address = elf_symbols()
    symbols = json.loads(SYMBOLS.read_text(encoding="utf-8"))
    # Generate everything first, so a draft that cannot be converted changes nothing.
    outputs = {name: (assembly(name, *gaps[name], by_name, by_address), c_source(name)) for name in names}
    ASM_DIR.mkdir(parents=True, exist_ok=True)
    SRC_DIR.mkdir(parents=True, exist_ok=True)
    for name in names:
        start, end = gaps[name]
        spec = json.loads((ROOT / "build" / "m2c" / name / "spec.json").read_text(encoding="utf-8"))
        cflags = [flag for flag in spec.get("cflags", []) if flag != "-w"]
        (ASM_DIR / f"{name}.inc").write_text(outputs[name][0], encoding="utf-8")
        (SRC_DIR / f"{name}.c").write_text(outputs[name][1], encoding="utf-8")
        entries.append({"name": name, "start": f"0x{start:06X}", "end": f"0x{end:06X}", "kind": "c", "compiler": "agbcc",
                        "cflags": cflags, "source": f"src/non_matching/{name}.c", "input_section": f".text.{name}",
                        "nonmatching": True,
                        "description": "Not matching yet: original assembly in a NONMATCH function, closest C attempt alongside"})
        # The function is now defined in source, not as an absolute symbol.
        symbols.pop(name, None)
        print(f"{name}: asm/non_matching/{name}.inc, src/non_matching/{name}.c ({end - start} bytes)")
    entries.sort(key=lambda entry: int(entry["start"], 0))
    SEGMENTS.write_text(json.dumps(entries, indent=2) + "\n", encoding="utf-8")
    SYMBOLS.write_text(json.dumps(symbols, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
