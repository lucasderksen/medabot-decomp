/* Native signed 8-bit mono PCM. Playback consumes bytes after this header.
 * 08073C18 uses rate/rateShift; 08073C3C uses rootNote; 08074118 tests
 * flags bit 0 and restarts at loopStart when length bytes have elapsed. */
struct SoundSampleHeader {
    u32 length;
    u16 rate;
    u8 rateShift;
    u8 rootNote;
    u32 flags;
    u32 loopStart;
};
typedef char SoundSampleHeaderSize[(sizeof(struct SoundSampleHeader) == 16) ? 1 : -1];

